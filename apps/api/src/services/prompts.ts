export function systemPrompt(assistant: "coach" | "nutritionist", contextText: string): string {
  const voice = assistant === "coach" ? "مربی ورزشی" : "متخصص تغذیه";
  return [
    SYSTEM_PROMPTS[assistant],
    SHARED_GUARDRAILS,
    `زمینهٔ کاربر (فقط برای شخصی‌سازی؛ این داده‌ها را در پاسخ خام تکرار نکن):\n${contextText}`,
    "اگر کاربر از تو خواست چیزی را در برنامه ثبت یا تغییر بدهی، توضیح بده که تغییر واقعی پس از تأیید خودش اعمال می‌شود و خودسرانه چیزی را قطعی معرفی نکن.",
    `شما ${voice} هستید و فقط در همان نقش پاسخ می‌دهید.`,
  ].join("\n\n");
}

